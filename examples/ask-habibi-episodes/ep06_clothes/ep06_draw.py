import math
from PIL import Image, ImageDraw

def louse(scale=1.0, col=(120, 90, 60)):
    s = scale; im = Image.new("RGBA", (int(220 * s), int(260 * s)), (0, 0, 0, 0)); d = ImageDraw.Draw(im); cx = 110 * s
    for k in range(3):
        for sx in (-1, 1):
            y = (110 + k * 40) * s; d.line((cx, y, cx + sx * 95 * s, y + sx * 0 + 35 * s), fill=(60, 40, 25, 255), width=int(9 * s))
    d.ellipse((cx - 55 * s, 90 * s, cx + 55 * s, 240 * s), fill=col + (255,), outline=(50, 34, 20, 255), width=int(6 * s))
    d.ellipse((cx - 32 * s, 30 * s, cx + 32 * s, 100 * s), fill=col + (255,), outline=(50, 34, 20, 255), width=int(6 * s))
    for sx in (-1, 1): d.ellipse((cx + sx * 14 * s - 7 * s, 52 * s, cx + sx * 14 * s + 7 * s, 66 * s), fill=(20, 14, 10, 255))
    for k in range(4): d.line((cx - 40 * s, (130 + k * 25) * s, cx + 40 * s, (130 + k * 25) * s), fill=(80, 56, 34, 255), width=int(4 * s))
    return im

